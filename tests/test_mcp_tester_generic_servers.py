def test_non_json_body_reports_content(mod):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        def do_POST(self):
            self.rfile.read(int(self.headers["Content-Length"]))
            raw = b"<html>proxy login</html>"
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.send_header("Content-Length", str(len(raw)))
            self.end_headers()
            self.wfile.write(raw)

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        client = mod.MCPClient(
            f"http://127.0.0.1:{server.server_address[1]}/mcp", protocol="legacy"
        )
        with pytest.raises(RuntimeError, match="not JSON.*text/html.*proxy login"):
            client.connect()
    finally:
        server.shutdown()
        server.server_close()


