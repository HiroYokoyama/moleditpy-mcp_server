def test_full_url_pasted_into_host_is_split(mod, monkeypatch):
    win = mod.MCPTesterWindow("http://127.0.0.1:7891/mcp")
    captured = {}
    monkeypatch.setattr(
        win, "_run", lambda fn, client, on_done: captured.setdefault("url", client.url)
    )
    win.host_edit.setText("https://example.org:8443/api/mcp")
    win._on_connect()
    assert captured["url"] == "https://example.org:8443/api/mcp"
    assert win.host_edit.text() == "example.org"
    assert win.scheme_combo.currentText() == "https"
    assert not win.refresh_btn.isEnabled()


