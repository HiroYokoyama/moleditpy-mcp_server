TOOLS = [{"name": f"tool_{i}", "inputSchema": {"type": "object"}} for i in range(5)]


class _Script:
    def __init__(
        self,
        sse=False,
        page_size=None,
        require_initialized=False,
        loop_cursor=False,
        negotiated="2025-06-18",
    ):
        self.sse = sse
        self.page_size = page_size
        self.require_initialized = require_initialized
        self.loop_cursor = loop_cursor
        self.negotiated = negotiated
        self.initialized = False
        self.requests: list = []


def _serve(script: _Script):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *args):  # silence
            pass

        def do_POST(self):
            body = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
            script.requests.append((body, self.headers))  # case-insensitive lookup
            method = body.get("method")
            if "id" not in body:  # notification
                if method == "notifications/initialized":
                    script.initialized = True
                self.send_response(202)
                self.end_headers()
                return
            if method == "initialize":
                result = {
                    "protocolVersion": script.negotiated,
                    "serverInfo": {"name": "scripted", "version": "1"},
                    "capabilities": {"tools": {}},
                }
            elif script.require_initialized and not script.initialized:
                self._reply(
                    {
                        "jsonrpc": "2.0",
                        "id": body["id"],
                        "error": {"code": -32600, "message": "not initialized"},
                    }
                )
                return
            elif method == "tools/list":
                if script.page_size is None:
                    result = {"tools": TOOLS}
                else:
                    start = int((body.get("params") or {}).get("cursor") or 0)
                    page = TOOLS[start : start + script.page_size]
                    result = {"tools": page}
                    nxt = start + script.page_size
                    if script.loop_cursor:
                        result["nextCursor"] = "0"
                    elif nxt < len(TOOLS):
                        result["nextCursor"] = str(nxt)
            elif method == "tools/call":
                result = {"content": [{"type": "text", "text": "called"}]}
            else:
                self._reply(
                    {
                        "jsonrpc": "2.0",
                        "id": body["id"],
                        "error": {"code": -32601, "message": "nope"},
                    }
                )
                return
            self._reply({"jsonrpc": "2.0", "id": body["id"], "result": result})

        def _reply(self, message):
            if script.sse:
                # A server notification first, then the response, split over
                # two data: lines, with a comment and a retry field mixed in.
                note = {
                    "jsonrpc": "2.0",
                    "method": "notifications/message",
                    "params": {"level": "info", "data": "hi"},
                }
                text = json.dumps(message, indent=1)
                data = "\n".join("data: " + line for line in text.splitlines())
                raw = (
                    ": keep-alive\n\nretry: 100\n\n"
                    f"event: message\ndata: {json.dumps(note)}\n\n"
                    f"event: message\n{data}\n\n"
                ).encode()
                ctype = "text/event-stream"
            else:
                raw = json.dumps(message).encode()
                ctype = "application/json"
            self.send_response(200)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(raw)))
            self.send_header("Mcp-Session-Id", "sess-1")
            self.end_headers()
            self.wfile.write(raw)

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, f"http://127.0.0.1:{server.server_address[1]}/mcp"


@pytest.fixture
def scripted():
    servers = []

    def _make(**kw):
        script = _Script(**kw)
        server, url = _serve(script)
        servers.append(server)
        return script, url

    yield _make
    for s in servers:
        s.shutdown()
        s.server_close()


def test_sse_framed_responses_are_decoded(mod, scripted):
    _script, url = scripted(sse=True)
    client = mod.MCPClient(url, protocol="legacy")
    info = client.connect()
    assert info["serverInfo"]["name"] == "scripted"
    assert [t["name"] for t in client.list_tools()] == [t["name"] for t in TOOLS]
    assert client.call_tool("tool_0", {})["content"][0]["text"] == "called"


def test_initialized_notification_is_sent(mod, scripted):
    script, url = scripted(require_initialized=True)
    client = mod.MCPClient(url, protocol="legacy")
    client.connect()
    assert script.initialized
    assert len(client.list_tools()) == len(TOOLS)
    note = [
        b for b, _ in script.requests if b.get("method") == "notifications/initialized"
    ]
    assert note and "id" not in note[0]


def test_negotiated_version_header_after_handshake(mod, scripted):
    script, url = scripted(negotiated="2025-06-18")
    client = mod.MCPClient(url, protocol="legacy")
    client.connect()
    client.list_tools()
    by_method = {b.get("method"): h for b, h in script.requests}
    assert "MCP-Protocol-Version" not in by_method["initialize"]
    assert by_method["tools/list"]["MCP-Protocol-Version"] == "2025-06-18"
    assert by_method["tools/list"]["Mcp-Session-Id"] == "sess-1"


def test_paginated_tools_list_is_followed(mod, scripted):
    script, url = scripted(page_size=2)
    client = mod.MCPClient(url, protocol="legacy")
    client.connect()
    assert [t["name"] for t in client.list_tools()] == [t["name"] for t in TOOLS]
    cursors = [
        (b.get("params") or {}).get("cursor")
        for b, _ in script.requests
        if b.get("method") == "tools/list"
    ]
    assert cursors == [None, "2", "4"]


def test_cursor_loop_terminates(mod, scripted):
    _script, url = scripted(page_size=2, loop_cursor=True)
    client = mod.MCPClient(url, protocol="legacy")
    client.connect()
    assert len(client.list_tools()) == 4  # first page + one follow before the repeat


def test_non_string_header_values_are_sent_as_text(mod, scripted):
    script, url = scripted()
    client = mod.MCPClient(
        url, headers={"X-Retries": 3, "X-Flag": True}, protocol="legacy"
    )
    client.connect()
    _, headers = script.requests[0]
    assert headers["X-Retries"] == "3" and headers["X-Flag"] == "True"


